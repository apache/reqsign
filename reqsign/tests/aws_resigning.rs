#![cfg(all(feature = "aws-v4", feature = "aws-v4a", feature = "default-crypto"))]

use std::time::Duration;

use anyhow::Result;
use http::{HeaderValue, Request, request::Parts};
use reqsign::aws::{v4, v4a};
use reqsign::time::Timestamp;
use reqsign::{Context, ErrorKind, RustCryptoProvider, SignRequest, Signer};
use v4::Credential;

const REGION: &str = "us-east-1";
const OBJECT_URI: &str = "https://example.com/object%2fkey";
const PRESIGN: Option<Duration> = Some(Duration::from_secs(60));
const BUSINESS_URI: &str = "https://example.com/object%2fkey?x-amz-date=business&X-Amz-Metadata=kept&uploadId=a%2fb%3d&literal=+&&dup=second&dup=first&empty=&flag&marker=?";

fn request(uri: &str) -> Parts {
    Request::get(uri)
        .version(http::Version::HTTP_2)
        .extension("fixture extension")
        .body(())
        .expect("fixture request must be valid")
        .into_parts()
        .0
}

fn business_request() -> Parts {
    let mut parts = request(BUSINESS_URI);
    parts.headers.insert(
        "x-amz-content-sha256",
        HeaderValue::from_static(v4::EMPTY_STRING_SHA256),
    );
    parts.headers.append(
        "x-amz-meta-label",
        HeaderValue::from_static("  first    value  "),
    );
    parts
        .headers
        .append("x-amz-meta-label", HeaderValue::from_static("second"));
    parts
}

fn credential(key: &str, token: Option<&str>) -> Credential {
    Credential {
        access_key_id: key.to_string(),
        secret_access_key: format!("fixture-secret-for-{key}"),
        session_token: token.map(str::to_owned),
        expires_in: None,
    }
}

fn v4_signer(time: Timestamp) -> v4::RequestSigner {
    v4::RequestSigner::new("s3", REGION).with_time(time)
}

fn v4a_signer(time: Timestamp) -> v4a::RequestSigner {
    v4a::RequestSigner::new("s3", v4a::SigningRegionSet::new(REGION).unwrap()).with_time(time)
}

fn static_signer(
    context: &Context,
    request_signer: impl SignRequest<Credential = Credential>,
    credential: &Credential,
) -> Signer<Credential> {
    let mut provider =
        v4::StaticCredentialProvider::new(&credential.access_key_id, &credential.secret_access_key);
    if let Some(token) = &credential.session_token {
        provider = provider.with_session_token(token);
    }
    Signer::new(context.clone(), provider, request_signer)
}

fn signers(time: &str) -> Result<[Signer<Credential>; 2]> {
    let time = time.parse()?;
    let context = Context::new().with_crypto(RustCryptoProvider::new());
    let credential = credential("fixture-access-key", None);
    Ok([
        static_signer(&context, v4_signer(time), &credential),
        static_signer(&context, v4a_signer(time), &credential),
    ])
}

