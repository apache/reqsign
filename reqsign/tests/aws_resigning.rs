async fn assert_resigning<S: SignRequest<Credential = Credential>>(
    new_signer: impl Fn(Timestamp) -> S,
) -> Result<()> {
    let context = Context::new().with_crypto(RustCryptoProvider::new());
    let first_time = "2024-12-31T23:59:59Z".parse()?;
    let retry_time = "2025-01-01T00:00:01Z".parse()?;
    let first = new_signer(first_time);
    let retry = new_signer(retry_time);
    let first_credential = Credential {
        expires_in: Some(first_time + Duration::from_secs(900)),
        ..credential("first-access-key", Some("first-token+/="))
    };

    for first_lifetime in [None, PRESIGN] {
        let mut signed = business_request();
        if first_lifetime.is_none() {
            // Sensitivity lets us check that a matching caller-supplied date is
            // kept on the first pass, even though the generated bytes would match.
            let mut date = HeaderValue::from_static("20241231T235959Z");
            date.set_sensitive(true);
            signed.headers.insert("x-amz-date", date);
        }
        first
            .sign_request(
                &context,
                &mut signed,
                Some(&first_credential),
                first_lifetime,
            )
            .await?;
        if first_lifetime.is_none() {
            assert!(signed.headers["x-amz-date"].is_sensitive());
        }

        let mut invalid = signed.clone();
        invalid
            .headers
            .insert("x-opaque", HeaderValue::from_bytes(b"\xff")?);
        let original = invalid.clone();
        let long_term = credential("long-term-access-key", None);
        let err = retry
            .sign_request(&context, &mut invalid, Some(&long_term), first_lifetime)
            .await
            .expect_err("an opaque signed header must fail after staging authentication");
        assert_eq!(err.kind(), ErrorKind::RequestInvalid);
        assert!(err.to_string().contains("invalid signed header value"));
        assert_request_unchanged(&invalid, &original);

        let signer = static_signer(&context, new_signer(retry_time), &long_term);
        for lifetime in [None, PRESIGN] {
            let err = signer
                .sign_with_credential(&mut invalid, &long_term, lifetime)
                .await
                .expect_err("signing with an explicit credential must also be atomic");
            assert_eq!(err.kind(), ErrorKind::RequestInvalid);
            assert!(err.to_string().contains("invalid signed header value"));
            assert_request_unchanged(&invalid, &original);
        }

        let replacement = credential("replacement-access-key", Some("new-token+=/"));
        for current_credential in [&long_term, &replacement] {
            let signer = static_signer(&context, new_signer(retry_time), current_credential);
            for retry_lifetime in [None, Some(Duration::from_secs(120))] {
                let mut fresh = business_request();
                signer.sign(&mut fresh, retry_lifetime).await?;
                let mut retried = signed.clone();
                signer.sign(&mut retried, retry_lifetime).await?;

                // Both algorithms use deterministic signatures with the RustCrypto provider.
                assert_eq!(
                    retried.uri, fresh.uri,
                    "{first_lifetime:?} -> {retry_lifetime:?}"
                );
                assert_eq!(
                    retried.headers, fresh.headers,
                    "{first_lifetime:?} -> {retry_lifetime:?}"
                );
                if retry_lifetime.is_some() {
                    assert!(
                        retried
                            .uri
                            .to_string()
                            .starts_with(&format!("{BUSINESS_URI}&"))
                    );
                    assert!(
                        retried
                            .uri
                            .query()
                            .unwrap()
                            .contains("X-Amz-Date=20250101T000001Z")
                    );
                } else {
                    assert_eq!(retried.uri, BUSINESS_URI);
                    assert_eq!(retried.headers["x-amz-date"], "20250101T000001Z");
                }
            }
        }
    }
    Ok(())
}

fn assert_request_unchanged(actual: &Parts, original: &Parts) {
    assert_eq!(actual.uri, original.uri);
    assert_eq!(actual.headers, original.headers);
    assert_eq!(actual.method, original.method);
    assert_eq!(actual.version, original.version);
    assert_eq!(
        actual.extensions.get::<&str>(),
        original.extensions.get::<&str>()
    );
}

#[tokio::test]
async fn retry_preserves_auth_named_fields_of_the_other_algorithm() -> Result<()> {
    let [first_v4, first_v4a] = signers("2024-12-31T23:59:59Z")?;
    let [next_v4, next_v4a] = signers("2025-01-01T00:00:01Z")?;

    let v4_input = request(&format!(
        "{OBJECT_URI}?%58-Amz-Region-Set=route%2fone&dup=a&dup=b"
    ));
    let mut v4a_input = request(&format!("{OBJECT_URI}?X-Amz-S3session-Token=caller-query"));
    v4a_input.headers.insert(
        "x-amz-s3session-token",
        HeaderValue::from_static("caller-header"),
    );
    // Set the payload header explicitly so both signing modes use the same one.
    v4a_input.headers.insert(
        "x-amz-content-sha256",
        HeaderValue::from_static(v4::EMPTY_STRING_SHA256),
    );

    for (input, first, next, first_mode) in [
        (v4_input, &first_v4, &next_v4, PRESIGN),
        (v4a_input.clone(), &first_v4a, &next_v4a, None),
        (v4a_input, &first_v4a, &next_v4a, PRESIGN),
    ] {
        let mut signed = input.clone();
        first.sign(&mut signed, first_mode).await?;
        for mode in [None, PRESIGN] {
            let mut retried = signed.clone();
            next.sign(&mut retried, mode).await?;
            let mut fresh = input.clone();
            next.sign(&mut fresh, mode).await?;
            assert_eq!(retried.uri, fresh.uri);
            assert_eq!(retried.headers, fresh.headers);
        }
    }
    Ok(())
}

#[tokio::test]
async fn s3_express_standard_authentication_preserves_the_caller_express_token() -> Result<()> {
    let context = Context::new().with_crypto(RustCryptoProvider::new());
    let first = static_signer(
        &context,
        v4::RequestSigner::new("s3express", REGION)
            .with_standard_session_token()
            .with_time("2024-12-31T23:59:59Z".parse()?),
        &credential("temporary-key", Some("fixture-token")),
    );
    let next = static_signer(
        &context,
        v4::RequestSigner::new("s3express", REGION)
            .with_standard_session_token()
            .with_time("2025-01-01T00:00:01Z".parse()?),
        &credential("long-term-key", None),
    );
    let mut input = request(&format!("{OBJECT_URI}?X-Amz-S3session-Token=caller-query"));
    input.headers.insert(
        "x-amz-s3session-token",
        HeaderValue::from_static("caller-header"),
    );
    for mode in [None, PRESIGN] {
        let mut retried = input.clone();
        first.sign(&mut retried, mode).await?;
        next.sign(&mut retried, mode).await?;
        let mut fresh = input.clone();
        next.sign(&mut fresh, mode).await?;
        assert_eq!(retried.uri, fresh.uri);
        assert_eq!(retried.headers, fresh.headers);
    }

    let mut ambiguous = input;
    first.sign(&mut ambiguous, PRESIGN).await?;
    // Change the order so neither token can be attributed to Reqsign's suffix.
    let query = ambiguous.uri.query().unwrap();
    let (query, signature) = query.rsplit_once('&').unwrap();
    ambiguous.uri = format!("{OBJECT_URI}?{signature}&{query}").parse()?;
    let original = ambiguous.clone();
    let error = next.sign(&mut ambiguous, None).await.unwrap_err();
    assert_eq!(error.kind(), ErrorKind::RequestInvalid);
    assert!(
        error
            .to_string()
            .contains("ambiguous fields in previous AWS query authentication")
    );
    assert_request_unchanged(&ambiguous, &original);
    Ok(())
}

#[tokio::test]
async fn first_header_signing_keeps_incomplete_query_authentication_fields() -> Result<()> {
    let uri = format!(
        "{OBJECT_URI}?operation=Read&X-Amz-Algorithm=AWS4-HMAC-SHA256&X-Amz-Signature=reference&X-Amz-Date=report&other=+"
    );
    for signer in signers("2024-12-31T23:59:59Z")? {
        let mut parts = request(&uri);
        signer.sign(&mut parts, None).await?;
        assert_eq!(parts.uri.to_string(), uri);
    }
    Ok(())
}

#[tokio::test]
async fn changing_presign_to_header_signing_keeps_recoverable_query_separators() -> Result<()> {
    for (first, next) in signers("2024-12-31T23:59:59Z")?
        .into_iter()
        .zip(signers("2025-01-01T00:00:01Z")?)
    {
        for (input_suffix, recovered_suffix) in [
            ("", ""),
            ("?", ""),
            ("?flag", "?flag"),
            ("?flag&", "?flag"),
            ("?flag&&", "?flag&&"),
            ("?&", "?&"),
            (
                "?dup=a%2fb&&dup=+&flag&empty=",
                "?dup=a%2fb&&dup=+&flag&empty=",
            ),
        ] {
            let mut parts = request(&format!("{OBJECT_URI}{input_suffix}"));
            first.sign(&mut parts, PRESIGN).await?;
            let mut represigned = parts.clone();
            first.sign(&mut represigned, PRESIGN).await?;
            assert_eq!(represigned.uri, parts.uri, "{input_suffix}");
            next.sign(&mut parts, None).await?;
            assert_eq!(
                parts.uri.to_string(),
                format!("{OBJECT_URI}{recovered_suffix}")
            );
        }
    }
    Ok(())
}

#[tokio::test]
async fn header_to_presign_keeps_an_indistinguishable_unsigned_payload_header() -> Result<()> {
    for signer in signers("2024-12-31T23:59:59Z")? {
        let mut fresh = request(OBJECT_URI);
        signer.sign(&mut fresh, PRESIGN).await?;
        assert!(
            fresh
                .uri
                .query()
                .unwrap()
                .split('&')
                .any(|pair| pair == "X-Amz-SignedHeaders=host")
        );
        assert!(!fresh.headers.contains_key("x-amz-content-sha256"));

        let mut generated = request(OBJECT_URI);
        let mut explicit = generated.clone();
        explicit.headers.insert(
            "x-amz-content-sha256",
            HeaderValue::from_static("UNSIGNED-PAYLOAD"),
        );
        signer.sign(&mut generated, None).await?;
        signer.sign(&mut explicit, None).await?;
        // The same serialized head can come from either form of input.
        assert_eq!(generated.uri, explicit.uri);
        assert_eq!(generated.headers, explicit.headers);

        signer.sign(&mut generated, PRESIGN).await?;
        signer.sign(&mut explicit, PRESIGN).await?;
        assert_eq!(generated.uri, explicit.uri);
        assert_eq!(generated.headers, explicit.headers);
        assert_eq!(
            generated.headers["x-amz-content-sha256"],
            "UNSIGNED-PAYLOAD"
        );
        assert!(
            generated
                .uri
                .query()
                .unwrap()
                .split('&')
                .any(|pair| pair == "X-Amz-SignedHeaders=host%3Bx-amz-content-sha256")
        );
    }
    Ok(())
}
