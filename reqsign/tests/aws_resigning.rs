#![cfg(all(feature = "aws-v4", feature = "aws-v4a", feature = "default-crypto"))]

use std::time::Duration;

use anyhow::Result;
use http::{HeaderValue, Request, request::Parts};
use reqsign::aws::{v4, v4a};
use reqsign::time::Timestamp;
use reqsign::{Context, ErrorKind, RustCryptoProvider, SignRequest, Signer};
use v4::Credential;

const REGION: &str = "us-east-1";
const BUSINESS_URI: &str = "https://example.com/object%2fkey?x-amz-date=business&X-Amz-Metadata=kept&uploadId=a%2fb%3d&literal=+&&dup=second&dup=first&empty=&flag&marker=?";

fn request() -> Parts {
    Request::get(BUSINESS_URI)
        .header("x-amz-content-sha256", v4::EMPTY_STRING_SHA256)
        .header("x-amz-meta-label", "  first    value  ")
        .header("x-amz-meta-label", "second")
        .version(http::Version::HTTP_2)
        .extension("fixture extension")
        .body(())
        .expect("fixture request must be valid")
        .into_parts()
        .0
}

fn credential(key: &str, token: Option<&str>) -> Credential {
    Credential {
        access_key_id: key.to_string(),
        secret_access_key: format!("fixture-secret-for-{key}"),
        session_token: token.map(str::to_owned),
        expires_in: None,
    }
}

#[tokio::test]
async fn sigv4_replaces_prior_authentication() -> Result<()> {
    assert_resigning(|time| v4::RequestSigner::new("s3", REGION).with_time(time)).await
}

#[tokio::test]
async fn sigv4a_replaces_prior_authentication() -> Result<()> {
    assert_resigning(|time| {
        v4a::RequestSigner::new("s3", v4a::SigningRegionSet::new(REGION).unwrap()).with_time(time)
    })
    .await
}

async fn assert_resigning<S: SignRequest<Credential = Credential>>(
    new_signer: impl Fn(Timestamp) -> S,
) -> Result<()> {
    let context = Context::new().with_crypto(RustCryptoProvider::new());
    let first_time = "2024-12-31T23:59:59Z".parse()?;
    let retry_time = "2025-01-01T00:00:01Z".parse()?;
    let first = new_signer(first_time);
    let retry = new_signer(retry_time);
    let first_credential = Credential {
        expires_in: Some(first_time + Duration::from_secs(900)),
        ..credential("first-access-key", Some("first-token+/="))
    };

    for first_lifetime in [None, Some(Duration::from_secs(60))] {
        let mut signed = request();
        if first_lifetime.is_none() {
            // Sensitivity lets us check that a matching caller-supplied date is
            // kept on the first pass, even though the generated bytes would match.
            let mut date = HeaderValue::from_static("20241231T235959Z");
            date.set_sensitive(true);
            signed.headers.insert("x-amz-date", date);
        }
        first
            .sign_request(
                &context,
                &mut signed,
                Some(&first_credential),
                first_lifetime,
            )
            .await?;
        if first_lifetime.is_none() {
            assert!(signed.headers["x-amz-date"].is_sensitive());
        }

        let mut invalid = signed.clone();
        invalid
            .headers
            .insert("x-opaque", HeaderValue::from_bytes(b"\xff")?);
        let original = invalid.clone();
        let long_term = credential("long-term-access-key", None);
        let err = retry
            .sign_request(&context, &mut invalid, Some(&long_term), first_lifetime)
            .await
            .expect_err("an opaque signed header must fail after staging authentication");
        assert_eq!(err.kind(), ErrorKind::RequestInvalid);
        assert!(err.to_string().contains("invalid signed header value"));
        assert_eq!(invalid.uri, original.uri);
        assert_eq!(invalid.headers, original.headers);
        assert_eq!(invalid.method, original.method);
        assert_eq!(invalid.version, original.version);
        assert_eq!(invalid.extensions.get::<&str>(), Some(&"fixture extension"));

        let replacement = credential("replacement-access-key", Some("new-token+=/"));
        for current_credential in [&long_term, &replacement] {
            let mut provider = v4::StaticCredentialProvider::new(
                &current_credential.access_key_id,
                &current_credential.secret_access_key,
            );
            if let Some(token) = &current_credential.session_token {
                provider = provider.with_session_token(token);
            }
            let signer = Signer::new(context.clone(), provider, new_signer(retry_time));
            for retry_lifetime in [None, Some(Duration::from_secs(120))] {
                let mut fresh = request();
                signer.sign(&mut fresh, retry_lifetime).await?;
                let mut retried = signed.clone();
                signer.sign(&mut retried, retry_lifetime).await?;

                // Both algorithms use deterministic signatures with the RustCrypto provider.
                assert_eq!(
                    retried.uri, fresh.uri,
                    "{first_lifetime:?} -> {retry_lifetime:?}"
                );
                assert_eq!(
                    retried.headers, fresh.headers,
                    "{first_lifetime:?} -> {retry_lifetime:?}"
                );
                if retry_lifetime.is_some() {
                    assert!(
                        retried
                            .uri
                            .to_string()
                            .starts_with(&format!("{BUSINESS_URI}&"))
                    );
                    assert!(
                        retried
                            .uri
                            .query()
                            .unwrap()
                            .contains("X-Amz-Date=20250101T000001Z")
                    );
                } else {
                    assert_eq!(retried.uri, BUSINESS_URI);
                    assert_eq!(retried.headers["x-amz-date"], "20250101T000001Z");
                }
            }
        }
    }
    Ok(())
}
